--********************************************************************************

CREATE TABLE IF NOT EXISTS proj_archive_room (
    code                    BIGINT PRIMARY KEY,
    orderindex              BIGINT DEFAULT 0 NOT NULL,
    legacy_doc_unid         VARCHAR(32),
    name                    VARCHAR(100) NOT NULL,
    alias                   VARCHAR(100) NOT NULL,
    x_length                DOUBLE NOT NULL,
    y_length                DOUBLE NOT NULL,
    h_length                DOUBLE NOT NULL,
    keyholders              TEXT,
    roommanagers            TEXT,
    remark                  VARCHAR(4000),
    pillarinfo              TEXT,
    doorsinfo               TEXT,
    windowsinfo             TEXT,
    sqlviewname             VARCHAR(100),
    listordercolumn         VARCHAR(100),
    initpostion_x           DOUBLE,
    initpostion_y           DOUBLE,
    initpostion_h           DOUBLE,
    initpostion_rot         DOUBLE,
    movestep                DOUBLE,
    locatedistance          DOUBLE,
    floortextureimage       VARCHAR(200),
    cabinetmovedistance     DOUBLE,
    elementname_cabinet     VARCHAR(30),
    elementname_side        VARCHAR(30),
    elementname_door        VARCHAR(30),
    elementname_layer       VARCHAR(30),
    createtime              VARCHAR(30),
    createuser              VARCHAR(100),
    lastmodifytime          VARCHAR(30),
    lastmodifyuser          VARCHAR(100),
    UNIQUE KEY uk_proj_archive_room_name (name),
    UNIQUE KEY uk_proj_archive_room_alias (alias)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS proj_archive_cabinet (
    code                    BIGINT PRIMARY KEY,
    legacy_doc_unid         VARCHAR(32),
    parentcode              BIGINT NOT NULL,
    name                    VARCHAR(100) NOT NULL,
    lenght                  DOUBLE NOT NULL,
    height                  DOUBLE NOT NULL,
    width                   DOUBLE NOT NULL,
    startx                  DOUBLE NOT NULL,
    starty                  DOUBLE NOT NULL,
    starth                  DOUBLE DEFAULT 0 NOT NULL,
    doornumberh             INT NOT NULL,
    doornumberv             INT NOT NULL,
    withdoor                TINYINT DEFAULT 0 NOT NULL,
    doortype                TINYINT DEFAULT 1 NOT NULL,
    cabinettype             TINYINT DEFAULT 1 NOT NULL,
    direction               TINYINT DEFAULT 1 NOT NULL,
    remark                  VARCHAR(4000),
    defaultleyercount       INT NOT NULL,
    defaultfolderwidth      DOUBLE NOT NULL,
    everydoorconfig         TEXT,
    doorheightpercents      VARCHAR(500),
    doorwidthpercents       VARCHAR(500),
    layerdirection          TINYINT DEFAULT 1 NOT NULL,
    doorrowdirection        TINYINT DEFAULT 1 NOT NULL,
    doorcolumndirection     TINYINT DEFAULT 1 NOT NULL,
    doornameformula         VARCHAR(200),
    doornameformula2        VARCHAR(200),
    doornamesize            VARCHAR(20),
    layernameformula        VARCHAR(200),
    layernameformula2       VARCHAR(200),
    layernamesize           VARCHAR(20),
    foldernamesize          VARCHAR(20),
    locationformula         VARCHAR(300),
    defaultfoldermode       TINYINT DEFAULT 1 NOT NULL,
    operatingside           TINYINT DEFAULT 0 NOT NULL,
    dooropendirection       TINYINT DEFAULT 1 NOT NULL,
    foldernamealign         TINYINT,
    folderordermode         TINYINT DEFAULT 0 NOT NULL,
    createtime              VARCHAR(30),
    createuser              VARCHAR(100),
    lastmodifytime          VARCHAR(30),
    lastmodifyuser          VARCHAR(100),
    UNIQUE KEY uk_proj_archive_cab_name (parentcode, name),
    CONSTRAINT fk_proj_archive_cab_room FOREIGN KEY (parentcode) REFERENCES proj_archive_room (code) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS proj_archive_location (
    code                    BIGINT PRIMARY KEY,
    parentdocunid           VARCHAR(32) NOT NULL,
    locdescription          VARCHAR(1000),
    typex                   TINYINT,
    roomcode                BIGINT NOT NULL,
    cabinetcode             BIGINT NOT NULL,
    roomalia                VARCHAR(100) NOT NULL,
    cabinetname             VARCHAR(100) NOT NULL,
    cabinetside             TINYINT NOT NULL,
    doorindex               INT NOT NULL,
    layerindex              INT NOT NULL,
    boxindex                INT NOT NULL,
    foldercount             INT DEFAULT 1 NOT NULL,
    orderindex              INT DEFAULT 1 NOT NULL,
    form_code               VARCHAR(64),
    record_rid              CHAR(36),
    record_title            VARCHAR(255),
    createtime              VARCHAR(30),
    createuser              VARCHAR(100),
    lastmodifytime          VARCHAR(30),
    lastmodifyuser          VARCHAR(100),
    UNIQUE KEY uk_proj_archive_loc_doc (parentdocunid),
    CONSTRAINT fk_proj_archive_loc_room FOREIGN KEY (roomcode) REFERENCES proj_archive_room (code) ON DELETE CASCADE,
    CONSTRAINT fk_proj_archive_loc_cab FOREIGN KEY (cabinetcode) REFERENCES proj_archive_cabinet (code) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS proj_archive_room_seq (stub CHAR(1) NOT NULL) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS proj_archive_cabinet_seq (stub CHAR(1) NOT NULL) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS proj_archive_location_seq (stub CHAR(1) NOT NULL) ENGINE=InnoDB;
